#!/bin/sh
# Joins the stylesheets listed in assets/css/order.txt (in that order) into assets/css/bundle.css, so each page makes one CSS request.
# Edit the small files, run this script, commit both. Needs only a POSIX shell: no Node.js.
cd "$(dirname "$0")/../assets/css" || exit 1
{
  echo "/* GENERATED by tools/bundle-css.sh from the files listed in order.txt. Edit those files, not this one. */"
  while read -r f; do [ -n "$f" ] && cat "$f" && echo; done < order.txt
} > bundle.css
echo "bundle.css: $(wc -c < bundle.css) bytes from $(grep -c . order.txt) files"
